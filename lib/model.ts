// The token radar's model, version radar-2: one sealed snapshot in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds
// pre-token protocols below the floor: the early rows the radar exists to find. A protocol is
// pre-token when its record carries no token (no market cap, no CoinGecko id, no symbol); the
// snapshot's live-token protocols are kept apart and shown as the market's own values, never mixed
// into the ranked board.
//
// Implied value follows only from the snapshot's own figures, in three parts:
//
//   base multiple : calibrated per category from the snapshot's own live-token protocols.
//                   For each category, take the median market-cap / TVL of its live-token
//                   protocols (each ratio winsorised at 5 so one outlier cannot set the
//                   category), then shrink it toward the global median by sample size, and
//                   clamp it to [0.05, 1.00]. A category with fewer than 3 live protocols
//                   takes the global median outright. No protocol name is ever special-cased:
//                   the multiple is a function of the category's own live comparables.
//   base          = tvl_usd x category_multiple
//   growth        = clamp(change_7d, -60, 120) per cent
//   growthMult    = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity      = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age unknown: 365 days)
//   implied       = max(1, round(base x growthMult x maturity))
//
// Why calibrate by category: a token's market value per dollar of TVL is not one number. In this
// snapshot the live-token median is 0.21 overall, but lending protocols trade near 0.13 of TVL
// while bridges trade near 0.56. A flat multiple would overvalue the first and undervalue the
// second. The calibration is recomputed from the snapshot on every run, so it is the snapshot's
// own evidence, not a hand-written list.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  /** How strongly a category's median is pulled toward the global median. */
  shrink_prior: number;
  /** A category needs this many live protocols before its own median is used. */
  min_live_for_category: number;
  /** One protocol's market-cap / TVL is capped here before the median is taken. */
  ratio_winsor: number;
  /** The calibrated multiple is clamped to this range. */
  multiple_floor: number;
  multiple_cap: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.5,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
  shrink_prior: 5,
  min_live_for_category: 3,
  ratio_winsor: 5,
  multiple_floor: 0.05,
  multiple_cap: 1.0,
};

